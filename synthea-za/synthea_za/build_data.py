"""Merge the per-language and per-province source files in ``data_src`` into the
package data directory used at run time.

Source layout (all committed, human editable):

* ``data_src/names/<language>.yml``: one language pool each (M, F, family lists and
  optional race sub-pools such as ``asian`` or ``other``).
* ``data_src/names/street.yml``: street names and street types.
* ``data_src/geography/<CODE>_demographics.csv``, ``<CODE>_zipcodes.csv`` and
  ``<CODE>_sdoh.csv`` per province code.
* ``data_src/providers/<CODE>_<kind>.csv`` per province and facility kind
  (hospitals, primary_care, urgent_care, dialysis, hospice, nursing, home_health).

Run ``python -m synthea_za.build_data`` from the ``synthea-za`` directory after editing
the sources. Validation is performed on the merged result.
"""
from __future__ import annotations

import csv
import random
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Set

from synthea_za.config import DATA_DIR, PROJECT_DIR, PROVINCES
from synthea_za.validate import validate_data_dir, _parse_simple_yaml_lists

SOURCE_DIR = PROJECT_DIR / "data_src"
PROVIDER_KINDS = ["hospitals", "primary_care", "urgent_care", "dialysis", "hospice", "nursing",
                  "home_health"]
# Languages whose speakers are Black African: the "black" sub pools of english and afrikaans
# are built from these pools so that a Black patient with English as home language still
# receives an African name.
AFRICAN_POOLS = ["zulu", "xhosa", "sepedi", "sesotho", "setswana", "xitsonga", "siswati",
                 "tshivenda", "isindebele"]
# Indian languages reuse the Indian South African pool kept under english.asian.
INDIAN_LANGUAGES = ["gujarati", "hindi", "tamil", "urdu", "telugu"]


def _yaml_list(items: Iterable[str]) -> str:
    cleaned = []
    for item in items:
        item = str(item).strip()
        if item:
            cleaned.append(item)
    return "[" + ", ".join(cleaned) + "]"


def _dedupe(items: Iterable[str]) -> List[str]:
    seen: Set[str] = set()
    result = []
    for item in items:
        key = item.lower()
        if key not in seen:
            seen.add(key)
            result.append(item)
    return result


def _sample(pools: Dict[str, Dict[str, object]], key: str, per_pool: int, seed: int) -> List[str]:
    rng = random.Random(seed)
    combined: List[str] = []
    for language in AFRICAN_POOLS:
        pool = pools.get(language, {})
        names = list(pool.get(key, []))  # type: ignore[arg-type]
        rng.shuffle(names)
        combined.extend(names[:per_pool])
    return _dedupe(sorted(combined))


def build_names(source: Path = SOURCE_DIR / "names", target: Path = DATA_DIR / "names.yml") -> None:
    pools: Dict[str, Dict[str, object]] = {}
    street: Dict[str, object] = {}
    for path in sorted(source.glob("*.yml")):
        data = _parse_simple_yaml_lists(path.read_text(encoding="utf-8"))
        for key, value in data.items():
            if key == "street":
                street.update(value)  # type: ignore[arg-type]
            else:
                pools[key] = value  # type: ignore[assignment]
    if "english" not in pools:
        raise SystemExit("data_src/names/english.yml is required")
    # derived pools
    for language in ("english", "afrikaans"):
        if language in pools and "black" not in pools[language]:
            pools[language]["black"] = {  # type: ignore[index]
                "M": _sample(pools, "M", 25, 1), "F": _sample(pools, "F", 25, 2),
                "family": _sample(pools, "family", 30, 3)}
    asian = pools["english"].get("asian")  # type: ignore[union-attr]
    if isinstance(asian, dict):
        for language in INDIAN_LANGUAGES:
            pools.setdefault(language, asian)
    lines = ["# Generated by synthea_za.build_data from data_src/names; do not edit by hand.",
             "# Each top level key is a language pool; nested keys are race specific sub pools."]
    for language in sorted(pools):
        pool = pools[language]
        lines.append(f"{language}:")
        for key in ("M", "F", "family"):
            if key in pool:
                lines.append(f"  {key}: {_yaml_list(_dedupe(pool[key]))}")  # type: ignore[arg-type]
        for key in sorted(k for k in pool if k not in ("M", "F", "family")):
            sub = pool[key]
            if isinstance(sub, dict):
                lines.append(f"  {key}:")
                for leaf in ("M", "F", "family"):
                    if leaf in sub:
                        lines.append(f"    {leaf}: {_yaml_list(_dedupe(sub[leaf]))}")
    lines.append("street:")
    for key in ("name", "type", "secondary"):
        if key in street:
            lines.append(f"  {key}: {_yaml_list(_dedupe(street[key]))}")  # type: ignore[arg-type]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _merge_csv(sources: List[Path], target: Path, renumber_id: bool = False,
               id_start: int = 1, sort_key=None) -> int:
    rows: List[Dict[str, str]] = []
    header: List[str] = []
    for path in sources:
        with path.open("r", encoding="utf-8-sig", newline="") as handle:
            reader = csv.DictReader(handle)
            if not header:
                header = list(reader.fieldnames or [])
            for row in reader:
                rows.append({column: (row.get(column) or "").strip() for column in header})
    if sort_key:
        rows.sort(key=sort_key)
    if renumber_id:
        for index, row in enumerate(rows):
            row["id"] = str(id_start + index)
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=header, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return len(rows)


def build_geography(source: Path = SOURCE_DIR / "geography", target: Path = DATA_DIR / "geography") -> Dict[str, int]:
    counts = {}
    for kind, name, extra in (("demographics", "demographics.csv", {}),
                              ("zipcodes", "zipcodes.csv", {}),
                              ("sdoh", "sdoh.csv", {})):
        files = [source / f"{p.code}_{kind}.csv" for p in PROVINCES if (source / f"{p.code}_{kind}.csv").is_file()]
        if not files:
            print(f"warning: no {kind} source files in {source}", file=sys.stderr)
            continue
        counts[kind] = _merge_csv(files, target / name, **extra)
    return counts


def build_providers(source: Path = SOURCE_DIR / "providers", target: Path = DATA_DIR / "providers") -> Dict[str, int]:
    counts = {}
    next_id = 100
    for kind in PROVIDER_KINDS:
        files = [source / f"{p.code}_{kind}.csv" for p in PROVINCES if (source / f"{p.code}_{kind}.csv").is_file()]
        if not files:
            continue
        counts[kind] = _merge_csv(files, target / f"{kind}.csv", renumber_id=True, id_start=next_id)
        next_id += counts[kind]
    return counts


def main(argv: List[str] | None = None) -> int:
    build_names()
    print("geography:", build_geography())
    print("providers:", build_providers())
    result = validate_data_dir(DATA_DIR)
    for issue in result.issues:
        print(str(issue))
    print("counts:", result.counts)
    print("OK" if result.ok else "FAILED")
    return 0 if result.ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
