"""Copy built in Synthea submodules that hard code United States assumptions into
``synthea_za/data/local_modules`` with South African values.

Currently handled:

* ``encounter/sdoh_hrsn``: the social needs screening treats everyone not born in the
  "US" as a likely refugee; the check now uses "ZA" and a lower share for people born
  elsewhere (most foreign born residents of South Africa are economic migrants).

Run from the ``synthea-za`` directory after updating the Synthea checkout:

    python tools/localise_builtin_modules.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
SYNTHEA_MODULES = HERE.parent / "src" / "main" / "resources" / "modules"
LOCAL_MODULES = HERE / "synthea_za" / "data" / "local_modules"


def localise_sdoh_hrsn() -> Path:
    source = SYNTHEA_MODULES / "encounter" / "sdoh_hrsn.json"
    module = json.loads(source.read_text(encoding="utf-8"))
    state = module["states"]["Q19"]
    branches = state["complex_transition"]
    patched = 0
    for branch in branches:
        condition = branch.get("condition", {})
        if condition.get("attribute") == "birth_country" and condition.get("value") == "US":
            condition["value"] = "ZA"
            patched += 1
        elif "condition" not in branch:
            # people born outside South Africa: a small share are refugees or asylum seekers
            for option in branch["distributions"]:
                if option["transition"] == "A19_Yes":
                    option["distribution"] = 0.02
                elif option["transition"] == "A19_No":
                    option["distribution"] = 0.975
    if patched != 1:
        raise SystemExit("sdoh_hrsn.json no longer matches the expected structure")
    module.setdefault("remarks", []).insert(0, "South African copy (synthea-za): the refugee screening question compares the birth country with ZA instead of US. Generated by tools/localise_builtin_modules.py.")
    target = LOCAL_MODULES / "encounter" / "sdoh_hrsn.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(module, indent=2) + "\n", encoding="utf-8")
    return target


if __name__ == "__main__":
    print("wrote", localise_sdoh_hrsn())
